#include "sentence/segmenter.h"
#include <vector>
using namespace foxlet::sentence;
void expect(const Segmenter&, std::string_view, std::vector<std::string_view>, Mode);
void measurementCases() {
  auto ru = [](std::string_view text, std::vector<std::string_view> expected) {
    expect(Segmenter("ru"), text, expected, Mode::Paragraph);
  };
  ru("Объём 5 куб. м, этого достаточно. Работа окончена.", {"Объём 5 куб. м, этого достаточно.", "Работа окончена."});
  ru("Нужно 50 куб. см жидкости. Затем перемешайте.", {"Нужно 50 куб. см жидкости.", "Затем перемешайте."});
  ru("Вместимость 2 куб.\u00a0дм. Бак полон.", {"Вместимость 2 куб.\u00a0дм.", "Бак полон."});
  ru("Купили 12 пог. м ткани. Заказ готов.", {"Купили 12 пог. м ткани.", "Заказ готов."});
  ru("Расход 2 кг/куб. м. Всё верно.", {"Расход 2 кг/куб. м.", "Всё верно."});
  ru("Мощность 100 л. с. при разгоне. Это предел.", {"Мощность 100 л. с. при разгоне.", "Это предел."});
  ru("Мощность 100 л.с. при разгоне.", {"Мощность 100 л.с. при разгоне."});
  ru("Мощность 100 л. с. Мы проверили.", {"Мощность 100 л. с.", "Мы проверили."});
  ru("Цена 20 долл. за штуку. Покупаем.", {"Цена 20 долл. за штуку.", "Покупаем."});
  ru("Цена 20 долл. Мы заплатили.", {"Цена 20 долл.", "Мы заплатили."});
  ru("Нужно 5 шт. на заказ. Этого хватит.", {"Нужно 5 шт. на заказ.", "Этого хватит."});
  ru("Осталось 5 шт. Мы закончили.", {"Осталось 5 шт.", "Мы закончили."});
  ru("Длина 30 см. Мы проверили.", {"Длина 30 см.", "Мы проверили."});
  ru("Площадь 25 кв. см. Мы проверили.", {"Площадь 25 кв. см.", "Мы проверили."});
  ru("Объём 10 куб.см. Затем проверим.", {"Объём 10 куб.см.", "Затем проверим."});
  ru("Единица — куб.\u00a0см. Это объём.", {"Единица — куб.\u00a0см.", "Это объём."});
  ru("Площадь 25 кв. см. ткани. Потом измерим.", {"Площадь 25 кв. см. ткани.", "Потом измерим."});
  ru("Длина 2,5 см. Затем измерим ширину.", {"Длина 2,5 см.", "Затем измерим ширину."});
  ru("Нужно 30 см. ткани. Потом измерим.", {"Нужно 30 см. ткани.", "Потом измерим."});
  ru("См. Иванов. Мы согласны.", {"См. Иванов.", "Мы согласны."});
  ru("Подробнее см. Иванов. Мы согласны.", {"Подробнее см. Иванов.", "Мы согласны."});
  ru("В пункте 2, см. Иванов. Мы согласны.", {"В пункте 2, см. Иванов.", "Мы согласны."});
  ru("Вес 2 кг. Мы проверили.", {"Вес 2 кг.", "Мы проверили."});
  ru("Добавьте 10 г сахара. Перемешайте.", {"Добавьте 10 г сахара.", "Перемешайте."});
  ru("Груз весит 10 т. Мы готовы.", {"Груз весит 10 т.", "Мы готовы."});
  ru("Скорость 60 км/ч. Мы едем.", {"Скорость 60 км/ч.", "Мы едем."});
  ru("Температура 20 °C. Мы измерили.", {"Температура 20 °C.", "Мы измерили."});
  for (auto lang : {"en", "zh", "ja", "ko", "ru"}) {
    expect(Segmenter(lang), "Area is 40 sq. ft inside. Next.", {"Area is 40 sq. ft inside.", "Next."}, Mode::Paragraph);
    expect(Segmenter(lang), "Volume is 20 cu. ft inside. Next.", {"Volume is 20 cu. ft inside.", "Next."}, Mode::Paragraph);
    expect(Segmenter(lang), "Volume is 20 cu. Next.", {"Volume is 20 cu.", "Next."}, Mode::Paragraph);
    expect(Segmenter(lang), "Mass is 10 kg. Next.", {"Mass is 10 kg.", "Next."}, Mode::Paragraph);
  }
  expect(Segmenter("ru", false), "Объём 5 куб. м.", {"Объём 5 куб.", "м."}, Mode::Paragraph);
  Segmenter custom("ru"); custom.setCustomRules("куб # NUMERIC_ONLY #\nсм\n");
  expect(custom, "Объём 5 куб. м.", {"Объём 5 куб.", "м."}, Mode::Paragraph);
  expect(custom, "Длина 30 см. Мы проверили.", {"Длина 30 см. Мы проверили."}, Mode::Paragraph);
}
