#include "sentence/segmenter.h"
#include <vector>
using namespace foxlet::sentence;
void expect(const Segmenter&, std::string_view, std::vector<std::string_view>, Mode);
void russianCases() {
  auto e = [](std::string_view input, std::vector<std::string_view> expected) {
    expect(Segmenter("ru"), input, expected, Mode::Paragraph);
  };
  e("Он вернулся. -- Где ключ?", {"Он вернулся.", "-- Где ключ?"});
  e("-- Где ключ? -- На столе.", {"-- Где ключ?", "-- На столе."});
  e("-- Где ключ? -- спросила она.", {"-- Где ключ? -- спросила она."});
  e("«Готово!» -- сказал он. Мы ушли.", {"«Готово!» -- сказал он.", "Мы ушли."});
  e("Вопрос? — «Ответ готов».", {"Вопрос?", "— «Ответ готов»."});
  e("Вопрос? -- \"Ответ готов\".", {"Вопрос?", "-- \"Ответ готов\"."});
  e("Вопрос? – „Ответ готов“.", {"Вопрос?", "– „Ответ готов“."});
  e("Вопрос? -- «ответ готов», -- сказал он.", {"Вопрос? -- «ответ готов», -- сказал он."});
  e("Готово. --\u00a0Дальше?", {"Готово.", "--\u00a0Дальше?"});
  e("Он ждал... -- Пора идти.", {"Он ждал...", "-- Пора идти."});
  e("Он ждал… -- сказал он тихо.", {"Он ждал… -- сказал он тихо."});
  e("Они ушли. 12 июня начался отпуск.", {"Они ушли.", "12 июня начался отпуск."});
  e("См. п. 2 и ст. 5 договора. Мы согласны.", {"См. п. 2 и ст. 5 договора.", "Мы согласны."});
  e("Телефон указан: тел. 12345, доб. 67.", {"Телефон указан: тел. 12345, доб. 67."});
  e("Художник (род. 1901, ум. 1980) жил здесь.", {"Художник (род. 1901, ум. 1980) жил здесь."});
  e("Значение 3.14. 20 человек согласились.", {"Значение 3.14.", "20 человек согласились."});
  e("Готово. @reader спасибо за помощь.", {"Готово.", "@reader спасибо за помощь."});
  e("Напишите @reader после обеда.", {"Напишите @reader после обеда."});
  e("Пиши a.b@example.com. Потом поговорим.", {"Пиши a.b@example.com.", "Потом поговорим."});
  e("Они ушли. «позже вернёмся», -- обещали они.", {"Они ушли.", "«позже вернёмся», -- обещали они."});
  e("И. о. директора прибыл. Мы начали.", {"И. о. директора прибыл.", "Мы начали."});
  e("Т. е. вопрос решён. Мы ушли.", {"Т. е. вопрос решён.", "Мы ушли."});
  e("Он согласен, т. есть можно начинать.", {"Он согласен, т. есть можно начинать."});
  e("Возьмём т. 2. Есть другие варианты.", {"Возьмём т. 2.", "Есть другие варианты."});
  e("В XIX в. люди писали письма. Теперь иначе.", {"В XIX в. люди писали письма.", "Теперь иначе."});
  e("Это было в XIX в. Мы проверили.", {"Это было в XIX в.", "Мы проверили."});
  e("В XIX–XX вв. появились новые методы.", {"В XIX–XX вв. появились новые методы."});
  e("Получено 3 млн. рублей. Они довольны.", {"Получено 3 млн. рублей.", "Они довольны."});
  e("Получено 3 млн. Мы довольны.", {"Получено 3 млн.", "Мы довольны."});
  e("Затраты составили 2 млрд. рублей.", {"Затраты составили 2 млрд. рублей."});
  e("Нужно 20 гр. сахара. Затем перемешать.", {"Нужно 20 гр. сахара.", "Затем перемешать."});
  e("Парк занимает 12 кв. км. Рядом озеро.", {"Парк занимает 12 кв. км.", "Рядом озеро."});
  e("Площадь комнаты 18 кв. м, окна выходят во двор.", {"Площадь комнаты 18 кв. м, окна выходят во двор."});
  e("Нужно 25 кв. см ткани. Этого хватит.", {"Нужно 25 кв. см ткани.", "Этого хватит."});
  e("Сечение равно 4 кв. мм. Это мало.", {"Сечение равно 4 кв. мм.", "Это мало."});
  e("Площадь 2,5 кв.\u00a0дм. Запишем ответ.", {"Площадь 2,5 кв.\u00a0дм.", "Запишем ответ."});
  e("Площадь 10 кв.м. Дом готов.", {"Площадь 10 кв.м.", "Дом готов."});
  e("Живу в кв. 12. Заходите завтра.", {"Живу в кв. 12.", "Заходите завтра."});
  e("Это отчёт за I кв. Мы закончили.", {"Это отчёт за I кв.", "Мы закончили."});
  expect(Segmenter("ru", false), "Площадь 18 кв. м.", {"Площадь 18 кв.", "м."}, Mode::Paragraph);
  Segmenter areaCustom("ru"); areaCustom.setCustomRules("кв # NUMERIC_ONLY #\n");
  expect(areaCustom, "Площадь 18 кв. м. Живу в кв. 12.", {"Площадь 18 кв.", "м.", "Живу в кв. 12."}, Mode::Paragraph);
  e("Книги и пр. лежат здесь. Мы ушли.", {"Книги и пр. лежат здесь.", "Мы ушли."});
  e("Это было в I в. н. э. задолго до нас.", {"Это было в I в. н. э. задолго до нас."});
  e("Это было в I в. н. э. Мы проверили.", {"Это было в I в. н. э.", "Мы проверили."});
  e("Они ушли. …Начался дождь.", {"Они ушли.", "…Начался дождь."});
  e("Он… кажется, уснул.", {"Он… кажется, уснул."});
  e("Он ждал… Потом ушёл.", {"Он ждал…", "Потом ушёл."});
  e("И. О. Петров вернулся. Мы ушли.", {"И. О. Петров вернулся.", "Мы ушли."});
  expect(Segmenter("ru", false), "тел. 12345, доб. 67.", {"тел.", "12345, доб.", "67."}, Mode::Paragraph);
  Segmenter custom("ru"); custom.setCustomRules("тел\n");
  expect(custom, "тел. Иванова. И. о. директора пришёл.", {"тел. Иванова.", "И.", "о.", "директора пришёл."}, Mode::Paragraph);
}
